#!/usr/bin/env python3
"""Repository policy applied by git hooks and CI. Standard library only.

This file works without the harness, so it protects people using plain git too.
"""

from __future__ import annotations

import fnmatch
import os
import re
import subprocess
import sys
import tomllib
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
POLICY = tomllib.loads((ROOT / ".githooks" / "policy.toml").read_text(encoding="utf-8"))
PROTECTED = set(POLICY["repo"]["protected_branches"])
IS_GAME = POLICY["repo"]["kind"] == "game"

COMMIT = re.compile(r"^(feat|fix|docs|style|refactor|perf|test|build|ci|chore|art|audio|level|revert)(\([a-z0-9._-]+\))?!?: \S.{0,71}$")
BRANCH = re.compile(r"^(feature/[a-z0-9][a-z0-9._-]*|hotfix/[a-z0-9][a-z0-9._-]*|release/\d+\.\d+\.\d+)$")
SECRET = re.compile(
    r"(ghp_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{40,}|sk-[A-Za-z0-9_-]{24,}|AKIA[0-9A-Z]{16}|xox[baprs]-[A-Za-z0-9-]{10,}|-----BEGIN [A-Z ]*PRIVATE KEY-----)"
)
RUNTIME_AI = re.compile(r"(api\.openai\.com|api\.anthropic\.com|generativelanguage\.googleapis|OPENAI_API_KEY|ANTHROPIC_API_KEY)")
BLOCKED_PATH = re.compile(r"^(Binaries|Intermediate|DerivedDataCache|Saved)/")
ZERO = "0" * 40
TEXT_LIMIT = 1024 * 1024


def git(*args: str, check: bool = True, stdin: str | None = None) -> str:
    result = subprocess.run(
        ["git", *args], cwd=ROOT, input=stdin if stdin is not None else "", text=True,
        encoding="utf-8", errors="replace", capture_output=True,
    )
    if check and result.returncode != 0:
        raise SystemExit(f"[policy] git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout.strip() if check else (result.stdout.strip() if result.returncode == 0 else "")


def succeeded(*args: str) -> bool:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True).returncode == 0


def report(problems: list[str]) -> int:
    for problem in problems:
        print(f"[policy] {problem}", file=sys.stderr)
    return 1 if problems else 0


def now() -> datetime:
    override = os.environ.get("HARNESS_NOW")
    if override:
        return datetime.fromisoformat(override.replace("Z", "+00:00"))
    return datetime.now(timezone.utc)


def is_pre_jam() -> bool:
    if not IS_GAME:
        return False
    return now() < datetime.fromisoformat(POLICY["contest"]["start_utc"].replace("Z", "+00:00"))


def pre_jam_problem(path: str) -> str | None:
    rules = POLICY.get("prejam", {})
    if path in rules.get("allowed", []) or path in rules.get("gameplay_allowed", []):
        return None
    if any(fnmatch.fnmatch(path, pattern) for pattern in rules.get("blocked", [])):
        return f"{path}: game content cannot exist before the jam starts (constraint C-01)."
    root = rules.get("gameplay_root")
    if root and path.startswith(root):
        return f"{path}: gameplay code cannot exist before the jam starts (constraint C-01)."
    return None


def naming_problem(path: str) -> str | None:
    naming = POLICY.get("naming")
    if not naming or not path.startswith("Content/") or any(path.startswith(prefix) for prefix in naming["exempt"]):
        return None
    name = Path(path).name
    suffix = Path(path).suffix.lower()
    if suffix == ".umap" and not name.startswith("L_"):
        return f"{path}: maps must start with L_ (docs/naming-conventions.md)."
    if suffix == ".uasset" and not any(name.startswith(prefix) for prefix in naming["prefixes"]):
        return f"{path}: unknown asset prefix (docs/naming-conventions.md)."
    return None


def path_problems(paths: list[str]) -> list[str]:
    problems = []
    for path in paths:
        if BLOCKED_PATH.match(path):
            problems.append(f"{path}: generated by the engine and must not be committed.")
            continue
        if is_pre_jam():
            problem = pre_jam_problem(path)
            if problem:
                problems.append(problem)
        problem = naming_problem(path)
        if problem:
            problems.append(problem)
    return problems


def content_problems(path: str, text: str) -> list[str]:
    problems = []
    if SECRET.search(text):
        problems.append(f"{path}: looks like it contains a secret.")
    if IS_GAME and path.startswith(("Source/", "Config/")) and RUNTIME_AI.search(text):
        problems.append(f"{path}: no external AI calls or keys in the game (constraint C-08).")
    return problems


def is_lfs(path: str) -> bool:
    return "filter: lfs" in git("check-attr", "filter", "--", path)


def commit_subject_problem(subject: str) -> str | None:
    if subject.startswith(("Merge ", "Revert ")):
        return None
    if not subject.isascii():
        return f"Commit subject must be plain English: {subject}"
    if not COMMIT.match(subject):
        return f"Commit subject must look like `feat(scope): add thing`: {subject}"
    return None


def cmd_commit_msg(message_file: str) -> int:
    text = Path(message_file).read_text(encoding="utf-8")
    subject = next((line for line in text.splitlines() if line.strip() and not line.startswith("#")), "")
    problem = commit_subject_problem(subject)
    return report([problem] if problem else [])


def cmd_pre_commit() -> int:
    branch = git("symbolic-ref", "--short", "-q", "HEAD", check=False)
    git_dir = Path(git("rev-parse", "--absolute-git-dir"))
    allowed = os.environ.get("HARNESS_ALLOW_PROTECTED") == "1" or os.environ.get("HARNESS_BOOTSTRAP") == "1"
    if branch in PROTECTED and not (git_dir / "MERGE_HEAD").exists() and not allowed and succeeded("rev-parse", "-q", "--verify", "HEAD"):
        return report([f"Do not commit directly to {branch}. Create a feature branch or use `h ship`."])

    changed = [line for line in git("diff", "--cached", "--name-only", "--no-renames", "--diff-filter=ACMR").splitlines() if line]
    problems = path_problems(changed)
    limit = POLICY["limits"]["max_non_lfs_mib"] * 1024 * 1024
    for path in changed:
        if is_lfs(path):
            continue
        size = int(git("cat-file", "-s", f":{path}"))
        if size > limit:
            problems.append(f"{path}: {size / 1048576:.1f} MiB and not tracked by Git LFS. Add its type to .gitattributes.")
        elif size <= TEXT_LIMIT:
            problems.extend(content_problems(path, git("show", f":{path}")))
    return report(problems)


def cmd_pre_push() -> int:
    problems = []
    allowed = os.environ.get("HARNESS_ALLOW_PROTECTED") == "1" or os.environ.get("HARNESS_BOOTSTRAP") == "1"
    for line in sys.stdin.read().splitlines():
        parts = line.split()
        if len(parts) != 4:
            continue
        _, local_sha, remote_ref, remote_sha = parts
        name = remote_ref.removeprefix("refs/heads/")
        if not remote_ref.startswith("refs/heads/"):
            if remote_ref.startswith("refs/tags/") and local_sha == ZERO:
                problems.append(f"Deleting tag {remote_ref} is blocked.")
            continue
        if local_sha == ZERO:
            if name in PROTECTED:
                problems.append(f"Deleting {name} is blocked.")
            continue
        if remote_sha != ZERO and succeeded("cat-file", "-e", remote_sha) and not succeeded("merge-base", "--is-ancestor", remote_sha, local_sha):
            problems.append(f"Non fast-forward push to {name} is blocked. History must stay intact (constraint C-03).")
        if name in PROTECTED and not allowed:
            problems.append(f"Direct pushes to {name} are blocked. Open a pull request with `h ship`.")
        elif name not in PROTECTED and not BRANCH.match(name):
            problems.append(f"Branch {name} must be feature/<name>, hotfix/<name> or release/x.y.z.")
    return report(problems)


def allowed_pr(head: str, base: str) -> bool:
    if base == "main":
        return head.startswith(("release/", "hotfix/"))
    return bool(BRANCH.match(head)) or head == "main"


def cmd_ci(base: str, head: str, branch: str, target: str) -> int:
    problems = []
    if not allowed_pr(branch, target):
        problems.append(f"A pull request from {branch} into {target} is not allowed (docs/branching.md).")
    for subject in filter(None, git("log", "--no-merges", "--format=%s", f"{base}..{head}").splitlines()):
        problem = commit_subject_problem(subject)
        if problem:
            problems.append(problem)
    changed = [line for line in git("diff", "--name-only", "--no-renames", "--diff-filter=ACMR", f"{base}...{head}").splitlines() if line]
    problems.extend(path_problems(changed))
    for path in changed:
        blob = f"{head}:{path}"
        size = int(git("cat-file", "-s", blob))
        if is_lfs(path):
            if size > 300 or not git("cat-file", "-p", blob).startswith("version https://git-lfs.github.com/spec/v1"):
                problems.append(f"{path}: must be stored through Git LFS. Run `git lfs install` and commit it again.")
        elif size <= TEXT_LIMIT:
            problems.extend(content_problems(path, git("cat-file", "-p", blob)))
    print(f"[policy] checked {len(changed)} changed files")
    return report(problems)


def main() -> int:
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command == "commit-msg":
        return cmd_commit_msg(sys.argv[2])
    if command == "pre-commit":
        return cmd_pre_commit()
    if command == "pre-push":
        return cmd_pre_push()
    if command == "ci":
        return cmd_ci(*sys.argv[2:6])
    print("usage: policy.py commit-msg <file> | pre-commit | pre-push | ci <base> <head> <branch> <target>", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
